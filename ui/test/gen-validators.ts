// `bun run gen:validators`: the YAML editor's schema validators, compiled ahead
// of time.
//
// The editor checks a document against its kind's generated schema and decides
// each `if` the completion walker meets. Compiling either in the browser needs
// `new Function`, so the page would have to allow 'unsafe-eval'. This writes the
// code ajv would have compiled, as ES modules the build carries, and the page's
// policy allows no eval (docs/SECURITY_MODEL.md).
//
// Run it after `go run ./internal/schemas/cmd/genschemas` changes a schema, and
// after a bump of ajv or ajv-formats. test/yamlValidators.test.ts regenerates
// both files and refuses a difference; TestSchemas_ValidatorsAreCurrent, in
// internal/schemas, refuses a schema hash the files do not carry.
import Ajv, { type Options } from 'ajv';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

type Json = Record<string, unknown>;

/** The schemas the editor reads, as bytes: the hash in each header is of these. */
export interface SchemaSources {
	Orkflow: string;
	Automation: string;
}

export const FILES = { Orkflow: 'orkflow.v1.json', Automation: 'automation.v1.json' } as const;
export const OUTPUTS = { validators: 'src/lib/yaml/validators.gen.ts', conditions: 'src/lib/yaml/conditions.gen.ts' } as const;

// The options lint.ts reads ajv's errors under. `verbose` is what puts the
// schema and the data on each error, which its sentences are made from.
export const VALIDATOR_OPTIONS: Options = { allErrors: true, strict: true, strictRequired: false, allowUnionTypes: true, verbose: true };
// A bare `if` subschema has no type of its own, which strict mode would refuse
// to compile out of its context; a condition needs only a yes or a no.
export const CONDITION_OPTIONS: Options = { strict: false, allErrors: false };
const CODE = { source: true, esm: true, lines: true } as const;

/** Where a key's value is not a schema but a map of them, so `if` there is a name. */
const SCHEMA_MAPS = new Set(['properties', 'patternProperties', 'definitions']);
/** Where a value is data, not a schema. */
const DATA_KEYS = new Set(['enum', 'const', 'default', 'examples']);

/** Every `if` subschema in a schema, in document order. */
export function conditionsIn(schema: unknown): Json[] {
	const found: Json[] = [];
	const visit = (node: unknown, parent: string) => {
		if (Array.isArray(node)) {
			node.forEach((item) => visit(item, ''));
			return;
		}
		if (!node || typeof node !== 'object') return;
		for (const [key, value] of Object.entries(node)) {
			const isMap = SCHEMA_MAPS.has(parent);
			if (!isMap && DATA_KEYS.has(key)) continue;
			if (!isMap && key === 'if' && value && typeof value === 'object') found.push(value as Json);
			visit(value, isMap ? '' : key);
		}
	};
	visit(schema, '');
	return found;
}

// The shape of the only helpers ajv's code asks for. A new one stops the
// generator here: it has to be seen, not silently left for the browser to fail.
const RUNTIME_MODULES = new Set(['ajv/dist/runtime/ucs2length', 'ajv/dist/runtime/equal', 'ajv-formats/dist/formats']);

/**
 * Ajv writes its helpers as `require(...)`, which a browser module cannot call.
 * Each becomes an import. `cjs` reads a CommonJS module's exports whichever way
 * the importer's bundler interoperates: Bun and Vite differ on what a default
 * import of an `__esModule` module is.
 */
function asModule(code: string): string {
	const modules = new Map<string, string>();
	const body = code
		.replace(/^"use strict";\s*/, '')
		.replace(/require\("([^"]+)"\)/g, (_, name: string) => {
			if (!RUNTIME_MODULES.has(name)) throw new Error(`gen-validators: ajv's code asks for ${name}, which this generator has not been told about`);
			if (!modules.has(name)) modules.set(name, `module${modules.size}`);
			return `cjs(${modules.get(name)})`;
		});
	if (modules.size === 0) return body;
	const imports = [...modules].map(([name, id]) => `import * as ${id} from '${name}';`).join('\n');
	return `${imports}\nconst cjs = (ns) => (ns.default && ns.default.__esModule ? ns.default : ns);\n${body}`;
}

function header(what: string, sources: SchemaSources): string {
	const hashes = (Object.keys(FILES) as (keyof SchemaSources)[]).map(
		(kind) => `// schema ${FILES[kind]} sha256:${createHash('sha256').update(sources[kind]).digest('hex')}`
	);
	return ['// @ts-nocheck', `// ${what}`, '// Generated by `cd ui && bun run gen:validators` from src/lib/schemas/; do not edit.', ...hashes, ''].join('\n');
}

/** The file holding each kind's whole validator, as `Orkflow` and `Automation`. */
export function generateValidators(sources: SchemaSources): string {
	const ajv = new Ajv({ ...VALIDATOR_OPTIONS, code: CODE });
	// Exactly the formats the generator emits (ui/test/authoredSchemas.test.ts).
	addFormats(ajv, ['date-time']);
	ajv.addSchema(JSON.parse(sources.Orkflow), 'Orkflow');
	ajv.addSchema(JSON.parse(sources.Automation), 'Automation');
	const code = standaloneCode(ajv, { Orkflow: 'Orkflow', Automation: 'Automation' });
	return `${header('Each kind’s schema validator, compiled ahead of time for src/lib/yaml/lint.ts.', sources)}${asModule(code)}\n`;
}

/** The file holding each distinct `if`'s validator, keyed by its JSON. */
export function generateConditions(sources: SchemaSources): string {
	const ajv = new Ajv({ ...CONDITION_OPTIONS, code: CODE });
	const names = new Map<string, string>();
	for (const source of [sources.Orkflow, sources.Automation]) {
		for (const condition of conditionsIn(JSON.parse(source))) {
			const key = JSON.stringify(condition);
			if (key.includes('"$ref"')) throw new Error(`gen-validators: an if with a $ref is not compiled on its own: ${key}`);
			if (names.has(key)) continue;
			const name = `c${names.size}`;
			names.set(key, name);
			ajv.addSchema(condition, name);
		}
	}
	const code = standaloneCode(ajv, Object.fromEntries([...names.values()].map((name) => [name, name])));
	const table = [...names].map(([key, name]) => `\t${JSON.stringify(key)}: ${name},`).join('\n');
	return `${header('Every if/then/else condition in the schemas, compiled ahead of time for src/lib/yaml/complete.ts.', sources)}${asModule(code)}\nexport const CONDITIONS = {\n${table}\n};\n`;
}

/** The two files, by their path under ui/. */
export function generate(sources: SchemaSources): Record<string, string> {
	return { [OUTPUTS.validators]: generateValidators(sources), [OUTPUTS.conditions]: generateConditions(sources) };
}

if (import.meta.main) {
	const ui = `${import.meta.dir}/..`;
	const read = (file: string) => readFileSync(`${ui}/src/lib/schemas/${file}`, 'utf8');
	const out = generate({ Orkflow: read(FILES.Orkflow), Automation: read(FILES.Automation) });
	for (const [path, code] of Object.entries(out)) writeFileSync(`${ui}/${path}`, code);
}
