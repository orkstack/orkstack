// probeOrkflow is the orkflow this test owns in the dev bucket. The name is
// stable; the VERSION is per-run, and that is not incidental. This document
// changes every run — its description carries a nonce, which is what proves
// the restarted engine served THIS run's apply and not an earlier leftover —
// and a stored version is immutable: re-applying different content
// under one version is refused with artifacts.ErrVersionExists, never written.
// So the nonce that makes the document new also has to make the version new.
// Each run leaves one small JSON behind instead of rewriting one object; that
// is the cost of a version meaning one document forever.
const probeOrkflowName = "engine-restart-probe"

// probeOrkflowVersion is unique to this process and this instant, so two runs
// — or two agents sharing the dev bucket — never contend for one version.
func probeOrkflowVersion() string {
	return fmt.Sprintf("0.1.0-%d-%d", os.Getpid(), time.Now().UnixNano())
}

func probeOrkflowYAML(version, nonce string) string {
	return fmt.Sprintf(`apiVersion: orkstack/v1
kind: Orkflow
name: %s
version: "%s"
description: %s
tasks:
  - id: fetch
    uses: http
    with:
      op: get
      url: "https://example.test/json"
`, probeOrkflowName, version, nonce)
}

// TestIntegration_EngineServesOrkflowsAppliedToAPreviousProcess is acceptance
// #2 and #4 end to end on the real binary: apply to engine A, stop engine A,
// start engine B, and read the orkflow back from engine B.
func TestIntegration_EngineServesOrkflowsAppliedToAPreviousProcess(t *testing.T) {
	temporal := requireTemporal(t)
	cfg := requireObjectStore(t)
	ctx, cancel := context.WithTimeout(context.Background(), 4*time.Minute)
	defer cancel()

	binary := buildOrk(t)
	version := probeOrkflowVersion()
	nonce := fmt.Sprintf("applied by pid %d at %s", os.Getpid(), time.Now().UTC().Format(time.RFC3339Nano))
	transcript := &strings.Builder{}
	fmt.Fprintf(transcript, "# ork restart: an orkflow applied to one engine process is served by the next\n")
	fmt.Fprintf(transcript, "# generated by: go test -tags=integration -p 1 ./cmd/ork/ -run EngineServesOrkflows\n")
	fmt.Fprintf(transcript, "# temporal: %s   orkflow store: s3://%s/%s/\n\n",
		temporal, cfg.S3Bucket, artifacts.OrkflowPrefix)

	// --- engine A: accepts the apply -------------------------------------
	addrA, clientA, logA := bootEngine(ctx, t, binary, temporal, "engine-A")

	applied, err := clientA.ApplyOrkflow(ctx, connect.NewRequest(&orkstackv1.ApplyOrkflowRequest{
		Yaml: probeOrkflowYAML(version, nonce),
	}))
	if err != nil {
		t.Fatalf("apply against engine A: %v", err)
	}
	if got := applied.Msg.GetOrkflow().GetDescription(); got != nonce {
		t.Fatalf("engine A applied description %q, want %q", got, nonce)
	}
	fmt.Fprintf(transcript, "$ engine A (%s): ApplyOrkflow %s@%s\n  description: %s\n\n",
		addrA, probeOrkflowName, version, nonce)

	// The definition is in the bucket, at the documented key, before any read.
	store, err := artifacts.NewS3OrkflowStore(ctx, cfg)
	if err != nil {
		t.Fatalf("open orkflow store: %v", err)
	}
	uri, err := store.URI(artifacts.DefaultNamespace, probeOrkflowName, version)
	if err != nil {
		t.Fatalf("orkflow URI: %v", err)
	}
	want := fmt.Sprintf("s3://%s/metadata/orkflows/%s/%s/%s.json",
		cfg.S3Bucket, artifacts.DefaultNamespace, probeOrkflowName, version)
	if uri != want {
		t.Fatalf("orkflow URI = %q, want %q", uri, want)
	}
	stored, err := store.Get(ctx, artifacts.DefaultNamespace, probeOrkflowName, version)
	if err != nil {
		t.Fatalf("read %s: %v", uri, err)
	}
	if stored.GetDescription() != nonce {
		t.Fatalf("%s holds description %q, want %q", uri, stored.GetDescription(), nonce)
	}
	fmt.Fprintf(transcript, "$ aws s3 cp %s -\n  (engine A wrote it: description matches)\n\n", uri)

	// --- the restart -----------------------------------------------------
	stopEngine(t, "engine-A")
	if conn, err := net.DialTimeout("tcp", addrA, 500*time.Millisecond); err == nil {
		conn.Close()
		t.Fatal("engine A still answers after shutdown")
	}
	fmt.Fprintf(transcript, "$ kill -INT <engine A>   # process gone, %s refuses connections\n\n", addrA)

	// --- engine B: never saw the apply -----------------------------------
	addrB, clientB, logB := bootEngine(ctx, t, binary, temporal, "engine-B")

	got, err := clientB.GetOrkflow(ctx, connect.NewRequest(&orkstackv1.GetOrkflowRequest{
		Name: probeOrkflowName,
	}))
	if err != nil {
		t.Fatalf("GetOrkflow against engine B: %v\nengine B log:\n%s", err, logB.String())
	}
	reloaded := got.Msg.GetOrkflow()
	if reloaded.GetVersion() != version || reloaded.GetDescription() != nonce {
		t.Fatalf("engine B served %s@%s (%q), want %s@%s (%q)",
			reloaded.GetName(), reloaded.GetVersion(), reloaded.GetDescription(),
			probeOrkflowName, version, nonce)
	}
	if len(reloaded.GetTasks()) != 1 || reloaded.GetTasks()[0].GetUses() != "http" {
		t.Fatalf("engine B served a truncated definition: %v", reloaded.GetTasks())
	}
	fmt.Fprintf(transcript, "$ engine B (%s): GetOrkflow %s\n  version: %s\n  description: %s\n  tasks: %d\n\n",
		addrB, probeOrkflowName, reloaded.GetVersion(), reloaded.GetDescription(), len(reloaded.GetTasks()))

	listed, err := clientB.ListOrkflows(ctx, connect.NewRequest(&orkstackv1.ListOrkflowsRequest{}))
	if err != nil {
		t.Fatalf("ListOrkflows against engine B: %v", err)
	}
	names := make([]string, 0, len(listed.Msg.GetOrkflows()))
	found := false
	for _, wf := range listed.Msg.GetOrkflows() {
		names = append(names, wf.GetName()+"@"+wf.GetVersion())
		if wf.GetName() == probeOrkflowName {
			found = true
		}
	}
	if !found {
		t.Fatalf("engine B does not list %q; listed %v", probeOrkflowName, names)
	}
	fmt.Fprintf(transcript, "$ engine B: ListOrkflows -> %d orkflows, including %s@%s\n\n",
		len(names), probeOrkflowName, version)

	// The boot log records the reload, so an operator can see what an engine
	// came up with.
	bootLine := findLogLine(logB.String(), "reloaded orkflows from durable store")
	if bootLine == "" {
		t.Fatalf("engine B did not log the reload:\n%s", logB.String())
	}
	if !strings.Contains(bootLine, probeOrkflowName+"@"+version) {
		t.Errorf("engine B boot log does not name the reloaded orkflow:\n%s", bootLine)
	}
	if !strings.Contains(bootLine, "s3://"+cfg.S3Bucket+"/metadata/orkflows/") {
		t.Errorf("engine B boot log does not name the store:\n%s", bootLine)
	}
	fmt.Fprintf(transcript, "engine A boot: %s\nengine B boot: %s\n",
		findLogLine(logA.String(), "reloaded orkflows from durable store"), bootLine)

	// Both boot reads say how long they took. A slow boot is a stall in the
	// object store's list, and the engine's own log is where a proof finds out
	// which of the two reads it was (cmd/ork openOrkflowStore, openNamespaceStore).
	for _, boot := range []struct {
		engine string
		log    *syncBuffer
	}{{"A", logA}, {"B", logB}} {
		for _, message := range []string{"reloaded orkflows from durable store", "namespace registry ready"} {
			line := findLogLine(boot.log.String(), message)
			if line == "" {
				t.Errorf("engine %s did not log %q:\n%s", boot.engine, message, boot.log.String())
				continue
			}
			if !strings.Contains(line, "list_took=") {
				t.Errorf("engine %s's %q line does not say how long its list took (list_took):\n%s",
					boot.engine, message, line)
			}
		}
	}

	writeRestartProof(t, transcript.String())
}

// requireTemporal returns the Temporal address, skipping when it is not up
// (failing instead under ORK_REQUIRE_INFRA; see infraAbsent).
func requireTemporal(t *testing.T) string {
	t.Helper()
	address := os.Getenv("ORK_TEMPORAL_ADDRESS")
	if address == "" {
		address = client.DefaultHostPort
	}
	conn, err := net.DialTimeout("tcp", address, 2*time.Second)
	if err != nil {
		infraAbsent(t, "temporal is not reachable at %s: %v; run `make infra-up`", address, err)
	}
	_ = conn.Close()
	return address
}

// requireObjectStore returns the S3 config, skipping when the object store is not up
// (failing instead under ORK_REQUIRE_INFRA; see infraAbsent).
func requireObjectStore(t *testing.T) artifacts.Config {
	t.Helper()
	cfg := artifacts.ConfigFromEnv()
	cfg.Backend = artifacts.BackendS3
	if _, err := url.Parse(cfg.S3Endpoint); err != nil {
		infraAbsent(t, "object store endpoint %q is not a URL: %v; run `make infra-up`", cfg.S3Endpoint, err)
	}
	health := strings.TrimRight(cfg.S3Endpoint, "/") + "/"
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
	defer cancel()
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, health, nil)
	if err != nil {
		infraAbsent(t, "object store (SeaweedFS) is not reachable at %s: %v; run `make infra-up`", health, err)
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		infraAbsent(t, "object store (SeaweedFS) is not reachable at %s: %v; run `make infra-up`", health, err)
	}
	defer resp.Body.Close()
	_, _ = io.Copy(io.Discard, resp.Body)
	if resp.StatusCode != http.StatusOK && resp.StatusCode != http.StatusForbidden {
		infraAbsent(t, "object store health %s returned %d; run `make infra-up`", health, resp.StatusCode)
	}
	return cfg
}

// buildOrk returns the engine under test (internal/testsupport/testbin).
func buildOrk(t *testing.T) string {
	t.Helper()
	return testbin.Path(t, "./cmd/ork")
}

// running engines, so a failing test still stops what it started.
var engines = map[string]*engineProcess{}

type engineProcess struct {
	cmd  *exec.Cmd
	log  *syncBuffer
	done chan struct{}
}

// syncBuffer is a log an exec.Cmd writes to while a test reads it.
type syncBuffer struct {
	mu  sync.Mutex
	buf strings.Builder
}

func (b *syncBuffer) Write(p []byte) (int, error) {
	b.mu.Lock()
	defer b.mu.Unlock()
	return b.buf.Write(p)
}

func (b *syncBuffer) String() string {
	b.mu.Lock()
	defer b.mu.Unlock()
	return b.buf.String()
}

// bootEngine runs the real ork binary until its API answers, and returns the
// address, a client for it, and the captured log.
//
// A boot that dies before it serves is retried: the Temporal SDK gives its
// startup health check a few seconds, and a busy dev cluster can miss it. A
// retry re-reads the bucket from scratch, so it never hides what this test
// measures.
func bootEngine(
	ctx context.Context,
	t *testing.T,
	binary, temporalAddress, name string,
	extraEnv ...string,
) (string, orkstackv1connect.OrkflowServiceClient, *syncBuffer) {
	t.Helper()
	const attempts = 3
	for attempt := 1; attempt <= attempts; attempt++ {
		address, process := startEngine(ctx, t, binary, temporalAddress, name, extraEnv...)
		client := orkflowClient(t, address)
		if err := waitForEngine(ctx, t, name, client, process); err == nil {
			return address, client, process.log
		} else if attempt == attempts {
			stopEngine(t, name)
			t.Fatalf("%s never served its API: %v\nlog:\n%s", name, err, process.log.String())
		} else {
			t.Logf("%s boot attempt %d failed (%v); retrying\nlog:\n%s",
				name, attempt, err, process.log.String())
		}
		stopEngine(t, name)
	}
	return "", nil, nil // unreachable: the last attempt fatals
}

// startEngine runs the real ork binary on a free loopback port, with
// extraEnv (KEY=value) after everything else, so it wins.
func startEngine(
	ctx context.Context,
	t *testing.T,
	binary, temporalAddress, name string,
	extraEnv ...string,
) (string, *engineProcess) {
	t.Helper()
	address := freeAddress(t)
	cmd := exec.CommandContext(ctx, binary)
	cmd.Env = append(os.Environ(),
		"ORK_HTTP_ADDR="+address,
		"ORK_TEMPORAL_ADDRESS="+temporalAddress,
		// Apply-time image resolution runs here (§4.3), and the built-in
		// catalog names references that are not published yet.
		localActivityCatalogEnv(t),
	)
	cmd.Env = append(cmd.Env, extraEnv...)
	log := &syncBuffer{}
	cmd.Stdout = log
	cmd.Stderr = log
	if err := cmd.Start(); err != nil {
		t.Fatalf("start %s: %v", name, err)
	}
	process := &engineProcess{cmd: cmd, log: log, done: make(chan struct{})}
	engines[name] = process
	go func() { _ = cmd.Wait(); close(process.done) }()
	t.Cleanup(func() { stopEngine(t, name) })
	return address, process
}

// stopEngine signals the process and waits for it to exit, so the next engine
// starts against a cluster this test is no longer polling.
func stopEngine(t *testing.T, name string) {
	t.Helper()
	process, running := engines[name]
	if !running {
		return
	}
	delete(engines, name)
	_ = process.cmd.Process.Signal(os.Interrupt)
	select {
	case <-process.done:
	case <-time.After(20 * time.Second):
		_ = process.cmd.Process.Kill()
		<-process.done
	}
	t.Logf("%s log:\n%s", name, process.log.String())
}

func freeAddress(t *testing.T) string {
	t.Helper()
	listener, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatalf("reserve port: %v", err)
	}
	defer listener.Close()
	return listener.Addr().String()
}

func orkflowClient(t *testing.T, address string) orkstackv1connect.OrkflowServiceClient {
	t.Helper()
	transport := &http.Transport{}
	transport.Protocols = new(http.Protocols)
	transport.Protocols.SetUnencryptedHTTP2(true)
	t.Cleanup(transport.CloseIdleConnections)
	return orkstackv1connect.NewOrkflowServiceClient(
		&http.Client{Transport: transport}, "http://"+address)
}

// waitForEngine polls the Connect API until the engine answers, and gives up
// as soon as the process exits: a dead engine will never answer. A slow boot
// is tolerated up to bootwait.Deadline and recorded with a WARN line past
// bootwait.WarnAfter, not absorbed.
func waitForEngine(
	ctx context.Context,
	t *testing.T,
	name string,
	client orkstackv1connect.OrkflowServiceClient,
	process *engineProcess,
) error {
	t.Helper()
	_, err := bootwait.Wait{What: name, Exited: process.done, Logf: t.Logf}.Until(ctx,
		func(ctx context.Context) error {
			_, err := client.ListOrkflows(ctx, connect.NewRequest(&orkstackv1.ListOrkflowsRequest{}))
			return err
		})
	return err
}

// findLogLine returns the first log line containing needle.
func findLogLine(log, needle string) string {
	for _, line := range strings.Split(log, "\n") {
		if strings.Contains(line, needle) {
			return strings.TrimSpace(line)
		}
	}
	return ""
}

// writeRestartProof records the scenario under ORK_PROOF_DIR when it is set.
func writeRestartProof(t *testing.T, transcript string) {
	t.Helper()
	proof.Write(t, "ork", "engine-restart.txt", []byte(transcript))
}
