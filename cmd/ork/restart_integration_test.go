// Restart coverage for the ork binary: orkflows applied to one engine process
// are served by the next one, because they live in S3 and not in the process.
//
// Run against the repo's local infrastructure (`make infra-up`):
//
//	go test -tags=integration -p 1 ./cmd/ork/ -count=1 -v
//
// The test skips (never fails) when Temporal or MinIO is not running. It starts
// a real engine, which polls the shared ork-tasks queue for workflow tasks, so
// run it with -p 1 (AGENTS.md §11.1). It submits no runs.
