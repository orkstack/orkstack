// The JSON Schema of an Orkflow document (docs/schemas/orkflow.v1.json;
// docs/DSL.md, "Editor support").
//
// What "generated" means here: every key at every level and its JSON type is
// reflected from the document structs this compiler decodes into, and every
// word list is read from the variable the compiler checks against. What the
// structs cannot say — which key is required, which takes a const, which binds
// a word list or a pattern, the data positions' schemas, and the descriptions
// — is kept in the path-keyed tables below, each held to the compiler or to
// docs/DSL.md by a test (schema_internal_test.go). A renamed yaml tag changes
// the reflected schema at once; a table entry left under the old path fails
// TestOrkflowSchema_HasEveryDocumentKey.

// SchemaDialect is the JSON Schema draft every authored-document schema uses.
const SchemaDialect = "http://json-schema.org/draft-07/schema#"

// SchemaComment marks every generated schema file.
const SchemaComment = "Generated by go run ./internal/schemas/cmd/genschemas from the parsers' key tables; do not edit."

// schemaRef is a JSON pointer to a definition in the same file.
func schemaRef(name string) map[string]any { return map[string]any{"$ref": "#/definitions/" + name} }

// textTypes is a key the compiler reads as text: yaml.v3 decodes any scalar
// into a Go string as its text, so `cpu: 2` and `PORT: 8080` compile and mean
// what they say (docs/DSL.md, "Editor support").
var textTypes = []any{"string", "number", "boolean"}

// annotation is what the reflection cannot say about one path.
type annotation struct {
	required   bool           // the parent requires this key
	constValue any            // the key's one value
	enum       []string       // the words the compiler reads
	pattern    *regexp.Regexp // a string's shape
	maxLength  int            // a string's bound
	notEnum    []string       // values the pattern admits and the compiler refuses
	typ        map[string]any // a schema replacing the reflected one
	minItems   int            // a list's lower bound
	keyPattern *regexp.Regexp // a map's key shape (propertyNames)
	keyMax     int            // a map's key bound
}

// joinWordsSorted are joinWords' keys, sorted.
func joinWordsSorted() []string {
	words := make([]string, 0, len(joinWords))
	for word := range joinWords {
		words = append(words, word)
	}
	sort.Strings(words)
	return words
}

// orkflowAnnotations is the annotation table, keyed by path: a key's name, a
