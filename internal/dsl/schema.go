var yamlNodeType = reflect.TypeOf(yaml.Node{})

// orkflowSchemaBuilder reflects the document structs into definitions.
type orkflowSchemaBuilder struct {
	annotations map[string]annotation
	data        map[string]map[string]any
	defs        map[string]any
	paths       map[string]bool // every reflected path, for the tests
	err         error
}

// structSchema is one struct's object schema; path is where it stands.
func (b *orkflowSchemaBuilder) structSchema(t reflect.Type, path string) map[string]any {
	properties := map[string]any{}
	var required []string
	for i := 0; i < t.NumField(); i++ {
		field := t.Field(i)
		tag := strings.Split(field.Tag.Get("yaml"), ",")[0]
		if tag == "" || tag == "-" {
			continue
		}
		at := tag
		if path != "" {
			at = path + "." + tag
		}
		b.paths[at] = true
		schema := b.typeSchema(field.Type, at)
		if text, ok := orkflowDescriptions[at]; ok {
			schema = withDescription(schema, text)
		}
		properties[tag] = schema
		if b.annotations[at].required {
			required = append(required, tag)
		}
	}
	out := map[string]any{"type": "object", "additionalProperties": false, "properties": properties}
	if len(required) > 0 {
		sort.Strings(required)
		out["required"] = required
	}
	return out
}

func withDescription(schema map[string]any, text string) map[string]any {
	if _, isRef := schema["$ref"]; isRef {
		// draft-07 ignores a $ref's siblings; wrap it.
		return map[string]any{"allOf": []any{schema}, "description": text}
	}
	out := make(map[string]any, len(schema)+1)
	for k, v := range schema {
		out[k] = v
	}
	out["description"] = text
	return out
}

// typeSchema is the schema of one Go type at path.
func (b *orkflowSchemaBuilder) typeSchema(t reflect.Type, path string) map[string]any {
	ann := b.annotations[path]
	if ann.typ != nil {
		return ann.typ
	}
	if t == yamlNodeType {
		schema, ok := b.data[path]
		if !ok {
			b.err = fmt.Errorf("dsl schema: the data position %s has no schema", path)
			return map[string]any{}
		}
		return schema
	}
	if t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	var out map[string]any
	switch t.Kind() {
	case reflect.String:
		out = map[string]any{"type": textTypes}
	case reflect.Int32, reflect.Int64, reflect.Int:
		out = map[string]any{"type": "integer"}
	case reflect.Float64:
		out = map[string]any{"type": "number"}
	case reflect.Bool:
		out = map[string]any{"type": "boolean"}
	case reflect.Slice:
		b.paths[path+"[]"] = true
		out = map[string]any{"type": "array", "items": b.typeSchema(t.Elem(), path+"[]")}
		if ann.minItems > 0 {
			out["minItems"] = ann.minItems
		}
	case reflect.Map:
		b.paths[path+".*"] = true
		out = map[string]any{"type": "object", "additionalProperties": b.typeSchema(t.Elem(), path+".*")}
		if ann.keyPattern != nil {
			names := map[string]any{"type": "string", "pattern": ann.keyPattern.String()}
			if ann.keyMax > 0 {
				names["maxLength"] = ann.keyMax
			}
			out["propertyNames"] = names
		}
	case reflect.Struct:
		name, ok := documentStructs[t]
		if !ok {
			b.err = fmt.Errorf("dsl schema: %s at %s has no definition", t, path)
			return map[string]any{}
		}
		if _, built := b.defs[name]; !built {
			b.defs[name] = map[string]any{} // break cycles
			b.defs[name] = b.structSchema(t, path)
		}
		return schemaRef(name)
	default:
		b.err = fmt.Errorf("dsl schema: %s at %s has no JSON type", t, path)
		return map[string]any{}
	}
	switch {
	case ann.constValue != nil:
		out = map[string]any{"const": ann.constValue}
	case len(ann.enum) > 0:
		out = map[string]any{"enum": append([]string(nil), ann.enum...)}
	}
	if ann.pattern != nil {
		out["pattern"] = ann.pattern.String()
	}
	if ann.maxLength > 0 {
		out["maxLength"] = ann.maxLength
	}
	if len(ann.notEnum) > 0 {
		out["not"] = map[string]any{"enum": append([]string(nil), ann.notEnum...)}
	}
	return out
}

// awaitForbiddenKeys and composeForbiddenKeys are the compiler's refusal
// tables (rules 15 and 27), read off a zero task.
func awaitForbiddenKeys() []string {
	var out []string
	for _, field := range awaitExecutionKeys(taskDocument{}) {
		out = append(out, field.key)
	}
	return out
}

func composeForbiddenKeys() []string {
	var out []string
	for _, field := range composeExecutionKeys(taskDocument{}) {
		out = append(out, field.key)
	}
	return out
}

func forbidding(keys []string) map[string]any {
	properties := map[string]any{}
	for _, key := range keys {
		properties[key] = false
	}
	return map[string]any{"properties": properties}
}

// OrkflowSchema is the JSON Schema of an Orkflow document, as a JSON tree.
// firstParty maps a builtin catalog name ("http") to the interface its
// image's label declares.
func OrkflowSchema(firstParty map[string]*orkstackv1.ActivityInterface) (map[string]any, error) {
	b, root := buildOrkflowSchema()
	if b.err != nil {
		return nil, b.err
	}
	task := b.defs["orkflow.task"].(map[string]any)
	task["if"] = map[string]any{"required": []any{"await"}, "properties": map[string]any{"await": true}}
	task["then"] = forbidding(awaitForbiddenKeys())
	task["else"] = map[string]any{"required": []any{"uses"}, "properties": map[string]any{"uses": true}}
	bindings := []any{map[string]any{
		"if": map[string]any{"required": []any{"uses"}, "properties": map[string]any{
			"uses": map[string]any{"type": "string", "pattern": "^" + regexp.QuoteMeta(OrkflowUsesPrefix)}}},
		"then": forbidding(composeForbiddenKeys()),
	}}
	names := make([]string, 0, len(firstParty))
	for name := range firstParty {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		def, requiresWith := withSchema(name, firstParty[name])
		b.defs["orkflow.with."+name] = def
		then := map[string]any{"properties": map[string]any{"with": schemaRef("orkflow.with." + name)}}
		if requiresWith {
			then["required"] = []any{"with"}
		}
		bindings = append(bindings, map[string]any{
			"if":   map[string]any{"required": []any{"uses"}, "properties": map[string]any{"uses": map[string]any{"const": name}}},
			"then": then,
		})
	}
	task["allOf"] = bindings

	b.defs["orkflow.template"] = map[string]any{"type": "string", "pattern": `\{\{`,
		"description": "A templated value (docs/DSL.md, \"Templating\"): the Orker renders it to a string, so its type is the image's to judge at run time."}
	b.defs["orkflow.input"] = map[string]any{
		"type": "object", "additionalProperties": false, "description": orkflowInputDescription,
		"properties": map[string]any{
			"type":     map[string]any{"enum": append([]string(nil), typeWords...)},
			"required": map[string]any{"type": "boolean"},
			"default":  map[string]any{},
		},
	}
	b.defs["orkflow.await.field"] = map[string]any{
		"type": "object", "additionalProperties": false, "required": []any{"type"},
		"description": "One key a completion must carry: `type` one of string, number, boolean, object, array, " +
			"and `required`. It declares no `default`.",
		"properties": map[string]any{
			"type":     map[string]any{"enum": append([]string(nil), typeWords...)},
			"required": map[string]any{"type": "boolean"},
		},
	}
	root["$schema"] = SchemaDialect
	root["$comment"] = SchemaComment
	root["title"] = "OrkStack Orkflow (" + APIVersion + ")"
	root["description"] = orkflowRootDescription
	root["definitions"] = b.defs
	return root, nil
}

// buildOrkflowSchema reflects the document structs: the root schema and the
// builder holding its definitions and every reflected path.
func buildOrkflowSchema() (*orkflowSchemaBuilder, map[string]any) {
	b := &orkflowSchemaBuilder{
		annotations: orkflowAnnotations(),
		data:        orkflowDataPositions(),
		defs:        map[string]any{},
		paths:       map[string]bool{},
	}
	root := b.structSchema(reflect.TypeOf(document{}), "")
	// The data positions' own keys, which the definitions above declare.
	for _, path := range []string{"inputs.*", "inputs.*.type", "inputs.*.required", "inputs.*.default",
		"tasks[].await.schema.*", "tasks[].await.schema.*.type", "tasks[].await.schema.*.required"} {
		b.paths[path] = true
	}
	return b, root
}

// fieldSchema is one first-party with: key: its declared types (a templated
// string admitted where the types do not include string), its documentary
// default and where it comes from.
func fieldSchema(name string, f *orkstackv1.FieldSchema) map[string]any {
	words := fieldTypes(f)
	var typ any = words[0]
	if len(words) > 1 {
		list := make([]any, 0, len(words))
		for _, word := range words {
			list = append(list, word)
		}
		typ = list
	}
	out := map[string]any{"type": typ}
	if !slices.Contains(words, "string") {
		out = map[string]any{"anyOf": []any{map[string]any{"type": typ}, schemaRef("orkflow.template")}}
	}
	if def := f.GetDefault(); def != nil {
		out["default"] = def.AsInterface()
	}
	out["description"] = "Declared by images/activity-" + name + "/interface.ork.yaml, the source of the image's interface label."
	return out
}

// withSchema is a first-party image's with: definition, and whether a task
// using it must write with: (a required key, or an op with no default).
func withSchema(name string, iface *orkstackv1.ActivityInterface) (map[string]any, bool) {
	fieldsOf := func(fields map[string]*orkstackv1.FieldSchema) (map[string]any, []any) {
		properties := map[string]any{}
		var required []string
		for _, key := range mapKeys(fields) {
			properties[key] = fieldSchema(name, fields[key])
			if fields[key].GetRequired() {
				required = append(required, key)
			}
		}
		list := make([]any, 0, len(required))
		for _, key := range required {
			list = append(list, key)
		}
		return properties, list
	}
	properties, required := fieldsOf(iface.GetFields())
	def := map[string]any{
		"type": "object", "additionalProperties": true, "properties": properties,
		"description": "The `with:` keys the first-party `" + name + "` image declares. A deployment whose activity " +
			"catalog maps `" + name + "` to another image is checked against that image's label by `orkctl orkflow validate`.",
	}
	ops := mapKeys(iface.GetOps())
	if len(ops) > 0 {
		op := map[string]any{"anyOf": []any{map[string]any{"enum": ops}, schemaRef("orkflow.template")}}
		if d := iface.GetDefaultOp(); d != "" {
			op["default"] = d
		} else {
			required = append(required, opKey)
		}
		properties[opKey] = op
		var allOf []any
		for _, name := range ops {
			opProperties, opRequired := fieldsOf(iface.GetOps()[name].GetFields())
			then := map[string]any{"properties": opProperties}
			if len(opRequired) > 0 {
				then["required"] = opRequired
			}
			allOf = append(allOf, map[string]any{
				"if":   map[string]any{"required": []any{opKey}, "properties": map[string]any{opKey: map[string]any{"const": name}}},
				"then": then,
			})
			if name == iface.GetDefaultOp() {
				allOf = append(allOf, map[string]any{
					"if":   map[string]any{"not": map[string]any{"required": []any{opKey}}},
					"then": then,
				})
			}
		}
		def["allOf"] = allOf
	}
	if len(required) > 0 {
		def["required"] = required
	}
	return def, len(required) > 0
}
