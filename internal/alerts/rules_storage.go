func temporalRules() []Rule {
	const g, c = "temporal", "temporal"
	eng := `ork_component="engine"`
	return []Rule{
		{
			Name: "TemporalUnreachable", Group: g, Component: c, Severity: Critical, For: "2m",
			Expr:        tFail + " / " + tTotal + " > 0.5",
			Summary:     "Most requests to Temporal fail.",
			Description: `Over half of the {{ $labels.ork_component }}'s requests to Temporal have failed for 2 minutes.`,
			Meaning:     "Temporal is down or unreachable from OrkStack.",
			Impact:      "Nothing new starts; running containers carry on until the heartbeat timeout. See Temporal outages, above.",
			Confirm:     "`orkctl pool list` shows `unknown (unreachable)`.",
			Fix:         "Restore Temporal or the route to it; nothing in OrkStack needs repair. Follow the recovery checks in Temporal outages, above.",
			Related:     []string{"TemporalPollFailures", "HeartbeatLosses", "#temporal-outages"},
			Cases: []Case{
				fire("all fail", "10m", out("ork_component", "engine"),
					s("temporal_request_total", eng, "0+10x20"), s("temporal_request_failure_total", eng+`,status_code="UNAVAILABLE"`, "0+10x20"),
					s("temporal_long_request_total", eng, "0+1x20"), s("temporal_long_request_failure_total", eng+`,status_code="UNAVAILABLE"`, "0+1x20")),
				quiet("healthy", "10m", s("temporal_request_total", eng, "0+10x20"), s("temporal_long_request_total", eng, "0+1x20")),
			},
		},
		{
			Name: "TemporalPollFailures", Group: g, Component: c, Severity: Warning, For: "5m",
			Expr:        rTemporal("temporal_long_request_failure_total") + " > 0",
			Summary:     "Polls of Temporal fail.",
			Description: `The {{ $labels.ork_component }}'s long polls of Temporal have failed for 5 minutes.`,
			Meaning:     "Engines and Orkers cannot poll for work: Temporal or its matching service is unreachable.",
			Impact:      "Nothing is dispatched while it lasts.",
			Confirm:     "`orkctl pool list`",
			Fix:         "See Temporal outages, above.",
			Related:     []string{"TemporalUnreachable", "#temporal-outages"},
			Cases: []Case{
				fire("failing", "20m", out("ork_component", "orker"), s("temporal_request_total", `ork_component="orker"`, "0+10x30"), s("temporal_long_request_failure_total", `ork_component="orker",status_code="UNAVAILABLE"`, "0+1x30")),
				quiet("healthy", "20m", s("temporal_request_total", `ork_component="orker"`, "0+10x30"), s("temporal_long_request_failure_total", `ork_component="orker",status_code="UNAVAILABLE"`, "4x30")),
			},
		},
		{
			Name: "TemporalRateLimited", Group: g, Component: c, Severity: Warning, For: "5m",
			Expr:        "sum " + by("ork_component") + ` (rate(temporal_request_failure_total{status_code="RESOURCE_EXHAUSTED"}[5m])) > 0`,
			Summary:     "Temporal rate-limits OrkStack.",
			Description: `Temporal has answered the {{ $labels.ork_component }}'s requests "resource exhausted" for 5 minutes.`,
			Meaning:     "The cluster's namespace or frontend limits are lower than OrkStack's load.",
			Impact:      "Submits and other calls answer `ResourceExhausted`; callers retry.",
			Confirm:     "`orkctl run submit` answers `ResourceExhausted`.",
			Fix:         "Raise the Temporal namespace's or frontend's rate limits, or lower the load.",
			Related:     []string{"ApiUnavailable"},
			Cases: []Case{
				fire("limited", "20m", out("ork_component", "engine"), s("temporal_request_failure_total", eng+`,status_code="RESOURCE_EXHAUSTED"`, "0+1x30")),
				quiet("other failures", "20m", s("temporal_request_failure_total", eng+`,status_code="NOT_FOUND"`, "0+1x30")),
			},
		},
	}
}
