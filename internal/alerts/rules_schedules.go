package alerts

func scheduleRules() []Rule {
	const g = "schedules"
	sch := `ork_namespace="n",ork_schedule="nightly"`
	wantSch := out("ork_namespace", "n", "ork_schedule", "nightly")
	hook := `ork_namespace="n",ork_webhook_id="w1"`
	wantHook := out("ork_namespace", "n", "ork_webhook_id", "w1")
	tenMin := func(c Case) Case { c.Interval = "10m"; return c }
	return []Rule{
		{
			Name: "ScheduleFiresFailing", Group: g, Component: "schedules", Severity: Warning, For: "0m",
			Expr: "(sum " + by("ork_namespace", "ork_schedule") + ` (increase(ork_schedule_fires_total{outcome=~"refused|unavailable"}[3h])) >= 3) unless ` +
				on("ork_namespace", "ork_schedule") + " (sum " + by("ork_namespace", "ork_schedule") + ` (increase(ork_schedule_fires_total{outcome="started"}[3h])) > 0)`,
			Summary:     "A schedule's fires start no runs.",
			Description: `Schedule "{{ $labels.ork_schedule }}" of namespace "{{ $labels.ork_namespace }}" fired at least 3 times in 3 hours and started no run. Namespaces exported to this sink only; with object labels off, the schedule is not named.`,
			Meaning:     "Each fire was refused (the Orkflow is gone, its inputs no longer validate, the namespace is held) or found the engine unavailable.",
			Impact:      "The schedule's work is not done.",
			Confirm:     "`orkctl schedule get NAME` shows its recent fires and why each was refused.",
			Fix:         "Fix the refusal reason: restore the Orkflow version, fix the schedule's input, or release the hold. `unavailable` is Temporal.",
			Related:     []string{"AdmissionRefusing", "TemporalUnreachable"},
			Cases: []Case{
				tenMin(fire("refused", "3h", wantSch, s("ork_schedule_fires_total", sch+`,outcome="refused"`, "0+1x20"))),
				tenMin(quiet("some started", "3h", s("ork_schedule_fires_total", sch+`,outcome="refused"`, "0+1x20"), s("ork_schedule_fires_total", sch+`,outcome="started"`, "0+1x20"))),
			},
		},
		{
			Name: "ScheduleFiresSkipped", Group: g, Component: "schedules", Severity: Info, For: "0m",
			Expr:        "sum " + by("ork_namespace", "ork_schedule") + ` (increase(ork_schedule_actions_skipped_total{ork_schedule_skip_reason="overlap"}[3h])) >= 3`,
			Summary:     "A schedule skips fires while its last run is still running.",
			Description: `Schedule "{{ $labels.ork_schedule }}" of namespace "{{ $labels.ork_namespace }}" skipped at least 3 fires in 3 hours because of its overlap policy.`,
			Meaning:     "Its runs take longer than its interval, and its overlap policy skips a fire while one runs.",
			Impact:      "Fewer runs than the schedule declares.",
			Confirm:     "`orkctl schedule get NAME` shows the skipped fires.",
			Fix:         "Nothing, if intended. Otherwise lengthen the interval, speed the runs up, or change `overlap:`.",
			Cases: []Case{
				tenMin(fire("overlapping", "3h", wantSch, s("ork_schedule_actions_skipped_total", sch+`,ork_schedule_skip_reason="overlap"`, "0+1x20"))),
				tenMin(quiet("rarely", "3h", s("ork_schedule_actions_skipped_total", sch+`,ork_schedule_skip_reason="overlap"`, "0x20"))),
			},
		},
		{
			Name: "ScheduleFiresMissed", Group: g, Component: "schedules", Severity: Warning, For: "0m",
			Expr:        "sum " + by("ork_namespace", "ork_schedule") + ` (increase(ork_schedule_actions_skipped_total{ork_schedule_skip_reason="catchup_window"}[1h])) > 0`,
			Summary:     "A schedule missed fires past its catch-up window.",
			Description: `Schedule "{{ $labels.ork_schedule }}" of namespace "{{ $labels.ork_namespace }}" missed fires that fell outside its catch-up window.`,
			Meaning:     "The cluster could not fire on time (an outage) for longer than the schedule's `catchup_window`.",
			Impact:      "Those fires never run.",
			Confirm:     "`orkctl schedule get NAME` shows the missed fires.",
			Fix:         "Backfill the missed range if it matters (`orkctl schedule backfill`); widen `catchup_window` for the next outage.",
			Related:     []string{"TemporalUnreachable"},
			Cases: []Case{
				fire("missed", "30m", wantSch, s("ork_schedule_actions_skipped_total", sch+`,ork_schedule_skip_reason="catchup_window"`, "0x10 1x30")),
				quiet("on time", "30m", s("ork_schedule_actions_skipped_total", sch+`,ork_schedule_skip_reason="catchup_window"`, "0x40")),
			},
		},
		{
			Name: "ScheduleFireLate", Group: g, Component: "schedules", Severity: Warning, For: "15m",
			Expr: "histogram_quantile(0.95, sum " + by("ork_namespace", "le") + " (rate(ork_schedule_fire_lag_seconds_bucket[15m]))) > 300 unless " +
				on("ork_namespace") + " sum " + by("ork_namespace") + ` (increase(ork_schedule_requests_total{action="backfill"}[1h])) > 0`,
			Summary:     "Schedules fire late.",
			Description: `The 95th percentile of how late namespace "{{ $labels.ork_namespace }}"'s schedules fired has been over 5 minutes for 15 minutes, with no backfill running.`,
			Meaning:     "Fires reach the engine well after their time: the cluster or the engine is slow.",
			Impact:      "Scheduled runs start late.",
			Confirm:     "`orkctl schedule list` shows each schedule's last and next fire.",
			Fix:         "Check Temporal's load and the engines' (TemporalRateLimited, ApiUnavailable).",
			Related:     []string{"TemporalRateLimited"},
			Cases: []Case{
				fire("late", "40m", out("ork_namespace", "n"),
					s("ork_schedule_fire_lag_seconds_bucket", sch+`,le="60"`, "0x60"),
					s("ork_schedule_fire_lag_seconds_bucket", sch+`,le="900"`, "0+1x60"),
					s("ork_schedule_fire_lag_seconds_bucket", sch+`,le="+Inf"`, "0+1x60")),
				quiet("a backfill", "40m",
					s("ork_schedule_fire_lag_seconds_bucket", sch+`,le="60"`, "0x60"),
					s("ork_schedule_fire_lag_seconds_bucket", sch+`,le="900"`, "0+1x60"),
					s("ork_schedule_fire_lag_seconds_bucket", sch+`,le="+Inf"`, "0+1x60"),
					s("ork_schedule_requests_total", `ork_namespace="n",action="backfill"`, "0x10 1x50")),
			},
		},
		{
			Name: "ScheduleOverdue", Group: g, Component: "schedules", Severity: Warning, For: "10m",
			Expr:        "min " + by("ork_namespace") + " (ork_schedule_next_fire_seconds) < time() - 600",
			Summary:     "A schedule's next fire is overdue.",
			Description: `A schedule of namespace "{{ $labels.ork_namespace }}" should have fired over 10 minutes ago and has not.`,
			Meaning:     "The cluster is not firing the schedule.",
			Impact:      "Its runs do not start.",
			Confirm:     "`orkctl schedule get NAME` shows its next fire in the past.",
			Fix:         "See Temporal outages, above; if the cluster is healthy, recreate the schedule with `orkctl automation apply`.",
			Related:     []string{"ScheduleFiresMissed", "#temporal-outages"},
			Cases: []Case{
				fire("overdue", "30m", out("ork_namespace", "n"), s("ork_schedule_next_fire_seconds", sch, "0x40")),
				quiet("in the future", "30m", s("ork_schedule_next_fire_seconds", sch, "3600x40")),
			},
		},
		{
			Name: "ScheduleCensusPartial", Group: g, Component: "schedules", Severity: Info, For: "15m",
			Expr:        "min " + by() + " (ork_schedule_census_coverage_ratio) < 1 or max " + by() + " (ork_schedule_census_unavailable_ratio) == 1",
			Summary:     "The schedule census reads only some schedules.",
			Description: "The engines' census of schedules has covered only some of them, or none, for 15 minutes.",
			Meaning:     "The census ran out of its budget or could not read the cluster's schedules.",
			Impact:      "ScheduleOverdue is blind to the schedules it did not read.",
			Confirm:     "`orkctl schedule list` answers for every schedule.",
			Fix:         "See CensusSkipped and CensusStale.",
			Related:     []string{"CensusSkipped", "CensusStale"},
			Cases: []Case{
				fire("half covered", "30m", out(), s("ork_schedule_census_coverage_ratio", "", "0.5x40")),
				quiet("all covered", "30m", s("ork_schedule_census_coverage_ratio", "", "1x40"), s("ork_schedule_census_unavailable_ratio", "", "0x40")),
			},
		},
		{
			Name: "WebhookFailing", Group: g, Component: "webhooks", Severity: Warning, For: "30m",
			Expr: "(sum " + by("ork_namespace", "ork_webhook_id") + ` (increase(ork_webhook_deliveries_total{outcome="final_failure"}[1h])) >= 3) unless ` +
				on("ork_namespace", "ork_webhook_id") + " (sum " + by("ork_namespace", "ork_webhook_id") + ` (increase(ork_webhook_deliveries_total{outcome="delivered"}[1h])) > 0)`,
			Summary:     "A webhook's deliveries all fail.",
			Description: `Webhook "{{ $labels.ork_webhook_id }}" of namespace "{{ $labels.ork_namespace }}" has failed at least 3 deliveries for good in an hour and delivered none. Namespaces exported to this sink only; with object labels off, the webhook is not named.`,
			Meaning:     "The receiver refuses or does not answer, past every retry.",
			Impact:      "Its subscribers miss run events.",
			Confirm:     "`orkctl webhook deliveries ID` shows each failed delivery's attempts and answers.",
			Fix:         "Fix the receiver, then `orkctl webhook redeliver` what it missed.",
			Related:     []string{"WebhookDestinationBlocked", "WebhookDeliveriesStuck"},
			Cases: []Case{
				fire("failing", "80m", wantHook, s("ork_webhook_deliveries_total", hook+`,outcome="final_failure"`, "0+1x90")),
				quiet("some delivered", "80m", s("ork_webhook_deliveries_total", hook+`,outcome="final_failure"`, "0+1x90"), s("ork_webhook_deliveries_total", hook+`,outcome="delivered"`, "0+1x90")),
			},
		},
		{
			Name: "WebhookDeliveriesPending", Group: g, Component: "webhooks", Severity: Warning, For: "10m",
			Expr:        "max " + by() + ` (ork_webhook_deliveries_pending{ork_age_over="5m"}) > 0`,
			Summary:     "Webhook deliveries have been pending over 5 minutes.",
			Description: "Some webhook deliveries have waited over 5 minutes, for 10 minutes.",
			Meaning:     "Deliveries are retrying against slow or failing receivers, or the engine cannot run them.",
			Impact:      "Subscribers hear of run events late.",
			Confirm:     "`orkctl webhook deliveries ID` shows the pending deliveries.",
			Fix:         "Check the receivers (WebhookFailing) and Temporal.",
			Related:     []string{"WebhookDeliveriesStuck", "WebhookFailing"},
			Cases: []Case{
				fire("pending", "20m", out(), s("ork_webhook_deliveries_pending", `ork_age_over="5m"`, "2x30")),
				quiet("none", "20m", s("ork_webhook_deliveries_pending", `ork_age_over="5m"`, "0x30")),
			},
		},
		{
			Name: "WebhookDeliveriesStuck", Group: g, Component: "webhooks", Severity: Critical, For: "0m",
			Expr:        "max " + by() + ` (ork_webhook_deliveries_pending{ork_age_over="1h"}) > 0`,
			Summary:     "Webhook deliveries have been pending over an hour.",
			Description: "Some webhook deliveries have waited over an hour.",
			Meaning:     "Deliveries are stuck: their workflows are not progressing.",
			Impact:      "Subscribers miss run events until they move.",
			Confirm:     "`orkctl webhook deliveries ID` shows the oldest pending deliveries.",
			Fix:         "Check Temporal and the engines; once they are healthy, the deliveries resume.",
			Related:     []string{"WebhookDeliveriesPending", "TemporalUnreachable"},
			Cases: []Case{
				fire("stuck", "5m", out(), s("ork_webhook_deliveries_pending", `ork_age_over="1h"`, "1x10")),
				quiet("none", "5m", s("ork_webhook_deliveries_pending", `ork_age_over="1h"`, "0x10")),
			},
		},
		{
			Name: "WebhookDestinationBlocked", Group: g, Component: "webhooks", Severity: Info, For: "0m",
			Expr:        NEW(`ork_webhook_attempts_total{ork_webhook_class="blocked"}`, "1h", "ork_namespace"),
			Summary:     "A webhook's destination is blocked by the network policy.",
			Description: `A webhook delivery of namespace "{{ $labels.ork_namespace }}" was not sent: its destination resolves to a network the deployment does not allow.`,
			Meaning:     "The receiver's address is outside `webhooks.allowed_networks`, or is a private address the policy refuses.",
			Impact:      "The webhook never delivers until its URL or the policy changes.",
			Confirm:     "`orkctl webhook list` shows the webhook's URL; `orkctl webhook deliveries ID` the refusals.",
			Fix:         "Point the webhook at an allowed address, or allow the network on purpose.",
			Related:     []string{"WebhookFailing"},
			Cases:       newCases("ork_webhook_attempts_total", `ork_namespace="n",ork_webhook_class="blocked"`, out("ork_namespace", "n")),
		},
		{
			Name: "WebhookNotQueued", Group: g, Component: "webhooks", Severity: Warning, For: "0m",
			Expr:        NEW("ork_webhook_not_queued_total", "15m", "ork_namespace", "reason"),
			Summary:     "Run events were not queued for webhook delivery.",
			Description: `Events of namespace "{{ $labels.ork_namespace }}" were not queued for delivery: {{ $labels.reason }}.`,
			Meaning:     "The engine could not encode or store a delivery's body, or could not start its delivery.",
			Impact:      "Subscribers miss those events; nothing retries them.",
			Confirm:     "`orkctl webhook deliveries ID` lacks them; kit: `ork_webhook_not_queued_total` by reason.",
			Fix:         "`body_unstored`: the object store. `not_started`: Temporal. Then redeliver what was missed.",
			Related:     []string{"ObjectStoreErrors", "TemporalUnreachable"},
			Cases:       newCases("ork_webhook_not_queued_total", `ork_namespace="n",reason="body_unstored"`, out("ork_namespace", "n", "reason", "body_unstored")),
		},
		{
			Name: "TriggerUnavailable", Group: g, Component: "triggers", Severity: Warning, For: "5m",
			Expr:        "sum " + by("ork_namespace") + ` (rate(ork_trigger_invocations_total{outcome="unavailable"}[5m])) > 0`,
			Summary:     "HTTP triggers answer unavailable.",
			Description: `Triggers of namespace "{{ $labels.ork_namespace }}" have answered unavailable for 5 minutes. Namespaces exported to this sink only.`,
			Meaning:     "The engine could not start the trigger's run: Temporal is unreachable.",
			Impact:      "Callers' requests start nothing; a caller that retries is safe.",
			Confirm:     "`orkctl trigger list` answers; a test call answers unavailable.",
			Fix:         "See Temporal outages, above.",
			Related:     []string{"TemporalUnreachable", "#temporal-outages"},
			Cases: []Case{
				fire("unavailable", "20m", out("ork_namespace", "n"), s("ork_trigger_invocations_total", `ork_namespace="n",outcome="unavailable"`, "0+1x30")),
				quiet("started", "20m", s("ork_trigger_invocations_total", `ork_namespace="n",outcome="started"`, "0+1x30")),
			},
		},
	}
}
