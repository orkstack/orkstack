package alerts

import (
	"fmt"
	"regexp"
	"strings"

	"go.yaml.in/yaml/v4"
)

// The rule files' names, relative to RulesDir. Alerts are one file per
// group, AlertsFile(group), each with its promtool test, AlertsTestFile(group):
// promtool evaluates every rule of a test's files at every step of every
// case, so a group's cases load only that group.
const (
	RulesDir        = "deploy/observability/prometheus/rules"
	RecordsFile     = "orkstack-records.yml"
	RecordsTestFile = "orkstack-records_test.yaml"
)

const header = "# Generated by `go run ./internal/alerts/cmd/genalerts` from internal/alerts.\n# Do not edit: TestAlerts_AreGenerated refuses a stale file.\n"

// AlertsFile is a group's rule file.
func AlertsFile(group string) string { return "orkstack-alerts-" + group + ".yml" }

// AlertsTestFile is a group's promtool test file.
func AlertsTestFile(group string) string { return "orkstack-alerts-" + group + "_test.yaml" }

// Anchor is an alert's anchor in docs/RUNBOOKS.md: the heading is the
// alert's full name, so the anchor is that name in lower case.
func Anchor(rule string) string { return strings.ToLower(Prefix + rule) }

// labelRef is a label written into an annotation.
var labelRef = regexp.MustCompile(`\{\{\s*\$labels\.([a-zA-Z_][a-zA-Z0-9_]*)\s*\}\}`)

type ruleFile struct {
	Groups []ruleGroup `yaml:"groups"`
}

type ruleGroup struct {
	Name  string      `yaml:"name"`
	Rules []yamlEntry `yaml:"rules"`
}

type yamlEntry struct {
	Alert       string            `yaml:"alert,omitempty"`
	Record      string            `yaml:"record,omitempty"`
	Expr        string            `yaml:"expr"`
	For         string            `yaml:"for,omitempty"`
	Labels      map[string]string `yaml:"labels,omitempty"`
	Annotations map[string]string `yaml:"annotations,omitempty"`
}

// annotations is a rule's annotations as Prometheus templates them.
func (r Rule) annotations() map[string]string {
	return map[string]string{
		"summary":     r.Summary,
		"description": r.Description,
		"runbook_url": RunbookBase + Anchor(r.Name),
		"dashboard":   DashboardPath,
	}
}

// labels is the rule's own labels.
func (r Rule) labels() map[string]string {
	return map[string]string{"severity": string(r.Severity), "component": r.Component}
}

// expand renders an annotation for one firing alert's labels, as
// Prometheus's template would for the {{ $labels.x }} form the tables use.
func expand(s string, labels map[string]string) string {
	return labelRef.ReplaceAllStringFunc(s, func(m string) string {
		return labels[labelRef.FindStringSubmatch(m)[1]]
	})
}

func marshal(v any) ([]byte, error) {
	// No line wrapping: a rule's expression stays on one line, as it is
	// read and searched.
	b, err := yaml.Dump(v, yaml.WithIndent(2), yaml.WithLineWidth(-1))
	if err != nil {
		return nil, err
	}
	return append([]byte(header), b...), nil
}

// groupsOf keeps the tables' order of groups and of rules within each.
func groupsOf(rules []Rule) []ruleGroup {
	var out []ruleGroup
	index := map[string]int{}
	for _, r := range rules {
		i, ok := index[r.Group]
		if !ok {
			i = len(out)
			index[r.Group] = i
			out = append(out, ruleGroup{Name: "orkstack-" + r.Group})
		}
		forValue := r.For
		if forValue == "0m" {
			forValue = ""
		}
		out[i].Rules = append(out[i].Rules, yamlEntry{
			Alert: Prefix + r.Name, Expr: r.Expr, For: forValue,
			Labels: r.labels(), Annotations: r.annotations(),
		})
	}
	return out
}

type testFile struct {
	RuleFiles          []string `yaml:"rule_files"`
	EvaluationInterval string   `yaml:"evaluation_interval"`
	// GroupEvalOrder evaluates the recording rules before the alerts that
	// read them, at every step.
	GroupEvalOrder []string   `yaml:"group_eval_order,omitempty"`
	Tests          []testCase `yaml:"tests"`
}

type testCase struct {
	Name        string          `yaml:"name"`
	Interval    string          `yaml:"interval"`
	InputSeries []inputSeries   `yaml:"input_series"`
	AlertTests  []alertTest     `yaml:"alert_rule_test,omitempty"`
	ExprTests   []promqlExprTst `yaml:"promql_expr_test,omitempty"`
}

type inputSeries struct {
	Series string `yaml:"series"`
	Values string `yaml:"values"`
}

type alertTest struct {
	EvalTime  string     `yaml:"eval_time"`
	Alertname string     `yaml:"alertname"`
	ExpAlerts []expAlert `yaml:"exp_alerts"`
}

type expAlert struct {
	ExpLabels      map[string]string `yaml:"exp_labels"`
	ExpAnnotations map[string]string `yaml:"exp_annotations"`
}

type promqlExprTst struct {
	Expr       string      `yaml:"expr"`
	EvalTime   string      `yaml:"eval_time"`
	ExpSamples []expSample `yaml:"exp_samples"`
}

type expSample struct {
	Labels string  `yaml:"labels"`
	Value  float64 `yaml:"value"`
}

func (r Rule) expected(fires []map[string]string) []expAlert {
	out := []expAlert{}
	for _, f := range fires {
		labels := map[string]string{}
		for k, v := range f {
			labels[k] = v
		}
		for k, v := range r.labels() {
			labels[k] = v
		}
		ann := map[string]string{}
		for k, v := range r.annotations() {
			ann[k] = expand(v, labels)
		}
		out = append(out, expAlert{ExpLabels: labels, ExpAnnotations: ann})
	}
	return out
}

// Files renders every generated file: the rule and test files, by their
// path under RulesDir, and the runbooks' generated part, by RunbooksFile.
func Files() (map[string][]byte, error) {
	rules, records := Rules(), Records()
	byName := map[string]Rule{}
	closed := map[string]bool{}
	for i, r := range rules {
		if i > 0 && rules[i-1].Group != r.Group {
			closed[rules[i-1].Group] = true
		}
		if closed[r.Group] {
			return nil, fmt.Errorf("alert %s: the rules of group %s are not together", r.Name, r.Group)
		}
		if r.Group == "records" {
			return nil, fmt.Errorf("alert %s: group records is the recording rules'", r.Name)
		}
		if _, dup := byName[r.Name]; dup {
			return nil, fmt.Errorf("alert %s is declared twice", r.Name)
		}
		byName[r.Name] = r
	}
	out := map[string][]byte{}
	groups := groupsOf(rules)
	for _, grp := range groups {
		name := strings.TrimPrefix(grp.Name, "orkstack-")
		b, err := marshal(ruleFile{Groups: []ruleGroup{grp}})
		if err != nil {
			return nil, err
		}
		out[AlertsFile(name)] = b
		var tests []testCase
		for _, r := range rules {
			if r.Group != name {
				continue
			}
			for _, c := range r.Cases {
				interval := c.Interval
				if interval == "" {
					interval = "1m"
				}
				tc := testCase{Name: Prefix + r.Name + ": " + c.Name, Interval: interval}
				for _, s := range c.Input {
					tc.InputSeries = append(tc.InputSeries, inputSeries(s))
				}
				tc.AlertTests = append(tc.AlertTests, alertTest{EvalTime: c.EvalAt, Alertname: Prefix + r.Name, ExpAlerts: r.expected(c.Fires)})
				for _, a := range c.Also {
					other, ok := byName[a.Rule]
					if !ok || other.Group != name {
						return nil, fmt.Errorf("alert %s case %q expects %s, which is not an alert of its group", r.Name, c.Name, a.Rule)
					}
					tc.AlertTests = append(tc.AlertTests, alertTest{EvalTime: c.EvalAt, Alertname: Prefix + other.Name, ExpAlerts: other.expected(a.Fires)})
				}
				tests = append(tests, tc)
			}
		}
		b, err = marshal(testFile{RuleFiles: []string{RecordsFile, AlertsFile(name)}, EvaluationInterval: "5m", GroupEvalOrder: []string{"orkstack-records", grp.Name}, Tests: tests})
		if err != nil {
			return nil, err
		}
		out[AlertsTestFile(name)] = b
	}
	var recs []yamlEntry
	for _, r := range records {
		recs = append(recs, yamlEntry{Record: r.Name, Expr: r.Expr})
	}
	var err error
	if out[RecordsFile], err = marshal(ruleFile{Groups: []ruleGroup{{Name: "orkstack-records", Rules: recs}}}); err != nil {
		return nil, err
	}
	var rtests []testCase
	for _, r := range records {
		for _, c := range r.Cases {
			tc := testCase{Name: r.Name + ": " + c.Name, Interval: "1m"}
			for _, s := range c.Input {
				tc.InputSeries = append(tc.InputSeries, inputSeries(s))
			}
			var want []expSample
			for _, s := range c.Want {
				want = append(want, expSample(s))
			}
			tc.ExprTests = []promqlExprTst{{Expr: c.Expr, EvalTime: c.EvalAt, ExpSamples: want}}
			rtests = append(rtests, tc)
		}
	}
	if out[RecordsTestFile], err = marshal(testFile{RuleFiles: []string{RecordsFile}, EvaluationInterval: "5m", Tests: rtests}); err != nil {
		return nil, err
	}
	out[RunbooksFile] = []byte(runbooks(rules))
	return out, nil
}
