package main

import (
	"bytes"
	"fmt"
	"go/format"
)

// render is the Go source of TablePath for rows above floor: the same rows
// give the same bytes.
func render(rows []Row, floor string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./internal/orker/cmd/gencdihooks; DO NOT EDIT.\n\n")
	b.WriteString("package orker\n\n")
	b.WriteString("// cdiHookFloor is the oldest NVIDIA Container Toolkit release whose\n")
	b.WriteString("// nvidia-cdi-hook an Orker accepts (gencdihooks.Floor).\n")
	fmt.Fprintf(&b, "const cdiHookFloor = %q\n\n", floor)
	b.WriteString("// cdiHookTable is every build of nvidia-cdi-hook at or above the floor that\n")
	b.WriteString("// NVIDIA's signed repository " + Repository + " serves,\n")
	b.WriteString("// signed by the key " + SigningKeyFingerprint + ".\n")
	b.WriteString("var cdiHookTable = []cdiHookBuild{\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "\t{Version: %q, Arch: %q, Packaging: %q, Package: %q, PackageDigest: %q, BinarySHA256: %q},\n",
			r.Version, r.Arch, r.Packaging, r.Package, r.PackageDigest, r.BinarySHA256)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
