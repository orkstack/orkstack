package docscheck

import (
	"encoding/json/v2"
	"io/fs"
	"path/filepath"
	"regexp"
	"strings"
	"testing"

	"github.com/orkstack/orkstack/internal/testsupport/must"
)

// genESHeader is the first line protoc-gen-es writes into every file it
// generates, naming its own version.
var genESHeader = regexp.MustCompile(`^// @generated by protoc-gen-es v(\S+) `)

// genESLocked is ui/bun.lock's resolution of @bufbuild/protoc-gen-es: the
// version `bun install` puts in ui/node_modules, which `make proto` runs.
var genESLocked = regexp.MustCompile(`"@bufbuild/protoc-gen-es": \["@bufbuild/protoc-gen-es@([^"]+)"`)

// TestGenES_HeadersMatchTheLockedGenerator: the UI client under ui/src/lib/gen
// was generated by the protoc-gen-es that ui/package.json and ui/bun.lock pin.
// A bump of the generator without a regeneration leaves the files naming the
// old one, and every `make proto` then rewrites all of them.
func TestGenES_HeadersMatchTheLockedGenerator(t *testing.T) {
	root := repoRoot(t)
	var manifest struct {
		DevDependencies map[string]string `json:"devDependencies"`
	}
	must.OK(t, json.Unmarshal([]byte(readFile(t, filepath.Join(root, "ui", "package.json"))), &manifest))
	pinned := manifest.DevDependencies["@bufbuild/protoc-gen-es"]
	if pinned == "" {
		t.Fatal("ui/package.json pins no @bufbuild/protoc-gen-es")
	}
	if !regexp.MustCompile(`^[0-9]+\.[0-9]+\.[0-9]+$`).MatchString(pinned) {
		t.Fatalf("ui/package.json gives @bufbuild/protoc-gen-es as %q: pin an exact version (AGENTS.md §11.1, step 3)", pinned)
	}
	locked := genESLocked.FindStringSubmatch(readFile(t, filepath.Join(root, "ui", "bun.lock")))
	if locked == nil {
		t.Fatal("ui/bun.lock resolves no @bufbuild/protoc-gen-es")
	}
	if locked[1] != pinned {
		t.Fatalf("ui/bun.lock resolves @bufbuild/protoc-gen-es %s, ui/package.json pins %s: run bun install in ui, then make tsgen", locked[1], pinned)
	}
	gen := filepath.Join(root, "ui", "src", "lib", "gen")
	files := 0
	must.OK(t, filepath.WalkDir(gen, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".ts") {
			return err
		}
		files++
		first, _, _ := strings.Cut(readFile(t, path), "\n")
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		switch m := genESHeader.FindStringSubmatch(first); {
		case m == nil:
			t.Errorf("%s does not open with protoc-gen-es's header: %q", rel, first)
		case m[1] != pinned:
			t.Errorf("%s was generated by protoc-gen-es v%s; ui/package.json and ui/bun.lock pin %s: regenerate with make tsgen", rel, m[1], pinned)
		}
		return nil
	}))
	if files == 0 {
		t.Fatalf("no generated file under %s", gen)
	}
}
