// Package apidocs renders docs/API.md, the reference of OrkStack's
// client-facing API, from the proto sources' own comments.
//
// What a client can reach is exactly what the services' methods take and
// return, followed transitively: every service in proto/orkstack/v1, every
// message and enum reachable from a method's request or response, nothing
// else. An engine-internal message no method carries is not part of the API
// and is never rendered. The comments are the proto's, unedited, so the
// reference says what the contract says (AGENTS.md §12: proto is the single
// source of truth for cross-process types). Only their form changes: a table
// cell's comment is joined onto one line, a type's leading and trailing
// comments are joined, and a `<` outside a code span is escaped so a
// placeholder such as <run id> reads as text rather than vanishing as HTML.
package apidocs

import (
	"bytes"
	"context"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/bufbuild/protocompile"
	"google.golang.org/protobuf/reflect/protoreflect"
)

// Path is where the reference lives, relative to the repository root.
const Path = "docs/API.md"

// protoRoot is the import root of the proto sources, relative to the
// repository root (buf.yaml's module path).
const protoRoot = "proto"

// Render reads every .proto file under root/proto and returns the reference.
func Render(root string) ([]byte, error) {
	files, err := compile(filepath.Join(root, protoRoot))
	if err != nil {
		return nil, err
	}
	var services []protoreflect.ServiceDescriptor
	for _, f := range files {
		for i := 0; i < f.Services().Len(); i++ {
			services = append(services, f.Services().Get(i))
		}
	}
	sort.Slice(services, func(i, j int) bool { return services[i].Name() < services[j].Name() })

	messages := map[protoreflect.FullName]protoreflect.MessageDescriptor{}
	enums := map[protoreflect.FullName]protoreflect.EnumDescriptor{}
	var visit func(m protoreflect.MessageDescriptor)
	visit = func(m protoreflect.MessageDescriptor) {
		if !ours(m.FullName()) || messages[m.FullName()] != nil || m.IsMapEntry() {
			return
		}
		messages[m.FullName()] = m
		fields := m.Fields()
		for i := 0; i < fields.Len(); i++ {
			reach(fields.Get(i), visit, enums)
		}
	}
	for _, s := range services {
		methods := s.Methods()
		for i := 0; i < methods.Len(); i++ {
			visit(methods.Get(i).Input())
			visit(methods.Get(i).Output())
		}
	}

	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("## Services\n\n")
	for _, s := range services {
		writeService(&b, s)
	}
	b.WriteString("## Messages\n\n")
	for _, name := range sortedNames(messages) {
		writeMessage(&b, messages[name])
	}
	b.WriteString("## Enums\n\n")
	for _, name := range sortedNames(enums) {
		writeEnum(&b, enums[name])
	}
	return bytes.TrimRight(b.Bytes(), "\n"), nil
}

const header = `# API reference

<!-- Generated by go run ./internal/apidocs/cmd/genapidocs from proto/orkstack/v1. Do not edit. -->

OrkStack's API is a set of [Connect](https://connectrpc.com) services served
by ` + "`ork`" + ` on one h2c port (` + "`:8080`" + ` by default), the same contract
` + "`orkctl`" + ` and the UI use ([UI_CLI_PARITY.md](./UI_CLI_PARITY.md)). This page
is generated from the proto sources' own comments: every service, and every
message and enum a service's methods take or return.

A method is called at ` + "`/orkstack.v1.<Service>/<Method>`" + `, for example
` + "`POST /orkstack.v1.RunService/SubmitRun`" + `. In JSON a field is spelled in
lowerCamelCase (` + "`task_runs`" + ` arrives as ` + "`taskRuns`" + `), and enums use the dialect
[JSON.md](./JSON.md) describes. A comment may name an engine-internal message
(such as ` + "`ExecuteTaskInput`" + `) that no method carries; it is not part of
the API and is not listed here. OrkStack does not authenticate callers; the
deployment's gateway does, and may assert a principal in ` + "`Ork-Principal`" + `
([ARCHITECTURE.md](../ARCHITECTURE.md)).

`

func compile(dir string) ([]protoreflect.FileDescriptor, error) {
	var names []string
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() && strings.HasSuffix(path, ".proto") {
			rel, err := filepath.Rel(dir, path)
			if err != nil {
				return err
			}
			names = append(names, filepath.ToSlash(rel))
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	if len(names) == 0 {
		return nil, fmt.Errorf("no .proto files under %s", dir)
	}
	sort.Strings(names)
	compiler := protocompile.Compiler{
		Resolver: protocompile.WithStandardImports(&protocompile.SourceResolver{
			ImportPaths: []string{dir},
			Accessor: func(path string) (io.ReadCloser, error) {
				return os.Open(path)
			},
		}),
		SourceInfoMode: protocompile.SourceInfoStandard,
	}
	linked, err := compiler.Compile(context.Background(), names...)
	if err != nil {
		return nil, fmt.Errorf("compile %s: %w", dir, err)
	}
	out := make([]protoreflect.FileDescriptor, 0, len(linked))
	for _, f := range linked {
		out = append(out, f)
	}
	return out, nil
}

func ours(name protoreflect.FullName) bool {
	return strings.HasPrefix(string(name), "orkstack.")
}

func reach(f protoreflect.FieldDescriptor, visit func(protoreflect.MessageDescriptor), enums map[protoreflect.FullName]protoreflect.EnumDescriptor) {
	if f.IsMap() {
		reach(f.MapKey(), visit, enums)
		reach(f.MapValue(), visit, enums)
		return
	}
	switch f.Kind() {
	case protoreflect.MessageKind, protoreflect.GroupKind:
		visit(f.Message())
	case protoreflect.EnumKind:
		if e := f.Enum(); ours(e.FullName()) {
			enums[e.FullName()] = e
		}
	}
}

func sortedNames[T any](m map[protoreflect.FullName]T) []protoreflect.FullName {
	names := make([]protoreflect.FullName, 0, len(m))
	for n := range m {
		names = append(names, n)
	}
	sort.Slice(names, func(i, j int) bool { return names[i] < names[j] })
	return names
}

// comment is a descriptor's leading comment, then its trailing one, with the
// comment markers' single leading space removed.
func comment(d protoreflect.Descriptor) string {
	loc := d.ParentFile().SourceLocations().ByDescriptor(d)
	var parts []string
	for _, c := range []string{loc.LeadingComments, loc.TrailingComments} {
		if c = strings.TrimSpace(dedent(c)); c != "" {
			parts = append(parts, c)
		}
	}
	return escapeHTML(strings.Join(parts, "\n\n"))
}

// escapeHTML escapes `<` outside code spans, where markdown would read a
// placeholder (<run id>, .inputs.<name>) as an HTML tag and drop it. Inside a
// code span an entity would not decode, and nothing needs escaping.
func escapeHTML(s string) string {
	parts := strings.Split(s, "`")
	for i := 0; i < len(parts); i += 2 {
		parts[i] = strings.ReplaceAll(parts[i], "<", "&lt;")
	}
	return strings.Join(parts, "`")
}

func dedent(c string) string {
	lines := strings.Split(c, "\n")
	for i, l := range lines {
		lines[i] = strings.TrimPrefix(l, " ")
	}
	return strings.Join(lines, "\n")
}

// cell is a comment fit for one table cell: one line, pipes escaped.
func cell(c string) string {
	c = strings.ReplaceAll(c, "|", `\|`)
	paragraphs := strings.Split(c, "\n\n")
	for i, p := range paragraphs {
		paragraphs[i] = strings.Join(strings.Fields(p), " ")
	}
	return strings.Join(paragraphs, "<br><br>")
}

var anchorUnsafe = regexp.MustCompile(`[^a-z0-9_-]+`)

// anchor is the id a renderer gives a type's heading (### Run.Task): the
// GitHub slug, lower case with the dot dropped and `_` kept. Two types whose
// names differ only by a dot would share it; proto's PascalCase names (buf
// lint STANDARD) leave none, and TestAPIDocs_EveryLinkResolves would catch one.
func anchor(name protoreflect.FullName) string {
	return anchorUnsafe.ReplaceAllString(strings.ToLower(short(name)), "")
}

func link(name protoreflect.FullName) string {
	if !ours(name) {
		return "`" + string(name) + "`"
	}
	return fmt.Sprintf("[`%s`](#%s)", short(name), anchor(name))
}

// short drops the package, keeping nested names (Run.Task).
func short(name protoreflect.FullName) string {
	return strings.TrimPrefix(string(name), "orkstack.v1.")
}

func writeService(b *bytes.Buffer, s protoreflect.ServiceDescriptor) {
	fmt.Fprintf(b, "### %s\n\n", s.Name())
	if c := comment(s); c != "" {
		fmt.Fprintf(b, "%s\n\n", c)
	}
	fmt.Fprintf(b, "Defined in `proto/%s`.\n\n", s.ParentFile().Path())
	b.WriteString("| Method | Request | Response | Description |\n|---|---|---|---|\n")
	methods := s.Methods()
	for i := 0; i < methods.Len(); i++ {
		m := methods.Get(i)
		in, out := link(m.Input().FullName()), link(m.Output().FullName())
		if m.IsStreamingClient() {
			in = "stream " + in
		}
		if m.IsStreamingServer() {
			out = "stream " + out
		}
		fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n", m.Name(), in, out, cell(comment(m)))
	}
	b.WriteString("\n")
}

func writeMessage(b *bytes.Buffer, m protoreflect.MessageDescriptor) {
	fmt.Fprintf(b, "### %s\n\n", short(m.FullName()))
	if c := comment(m); c != "" {
		fmt.Fprintf(b, "%s\n\n", c)
	}
	fields := m.Fields()
	if fields.Len() == 0 {
		b.WriteString("No fields.\n\n")
		return
	}
	b.WriteString("| Field | Type | Description |\n|---|---|---|\n")
	for i := 0; i < fields.Len(); i++ {
		f := fields.Get(i)
		desc := cell(comment(f))
		if o := f.ContainingOneof(); o != nil && !o.IsSynthetic() {
			note := fmt.Sprintf("One of `%s`.", o.Name())
			if desc == "" {
				desc = note
			} else {
				desc = note + " " + desc
			}
		}
		fmt.Fprintf(b, "| `%s` | %s | %s |\n", f.Name(), typeOf(f), desc)
	}
	b.WriteString("\n")
}

func typeOf(f protoreflect.FieldDescriptor) string {
	if f.IsMap() {
		return fmt.Sprintf("map&lt;%s, %s&gt;", scalar(f.MapKey()), scalar(f.MapValue()))
	}
	t := scalar(f)
	if f.IsList() {
		return "repeated " + t
	}
	if f.HasOptionalKeyword() {
		return "optional " + t
	}
	return t
}

func scalar(f protoreflect.FieldDescriptor) string {
	switch f.Kind() {
	case protoreflect.MessageKind, protoreflect.GroupKind:
		return link(f.Message().FullName())
	case protoreflect.EnumKind:
		return link(f.Enum().FullName())
	default:
		return "`" + f.Kind().String() + "`"
	}
}

func writeEnum(b *bytes.Buffer, e protoreflect.EnumDescriptor) {
	fmt.Fprintf(b, "### %s\n\n", short(e.FullName()))
	if c := comment(e); c != "" {
		fmt.Fprintf(b, "%s\n\n", c)
	}
	b.WriteString("| Value | Number | Description |\n|---|---|---|\n")
	values := e.Values()
	for i := 0; i < values.Len(); i++ {
		v := values.Get(i)
		fmt.Fprintf(b, "| `%s` | %d | %s |\n", v.Name(), v.Number(), cell(comment(v)))
	}
	b.WriteString("\n")
}
